#!/usr/bin/env python3
"""Builds docs/DATA_MODEL.md from the object and field metadata in force-app, plus the hand-kept change log
(docs/data_model_log.md) and the snapshot of dev fields that live outside this repo (tools/dev_fields_outside_repo.json).
Run from the repo root: python3 tools/data_model.py"""
import json, os, xml.etree.ElementTree as ET
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OBJ = os.path.join(ROOT, 'force-app/main/default/objects')
NS = '{http://soap.sforce.com/2006/04/metadata}'

def text(el, tag):
    x = el.find(NS + tag)
    return x.text.strip() if x is not None and x.text else ''

def field_row(path):
    el = ET.parse(path).getroot()
    name = os.path.basename(path).replace('.field-meta.xml', '')
    t = text(el, 'type') or ('Formula' if text(el, 'formula') else '')
    detail = []
    if t in ('Text', 'LongTextArea', 'TextArea'):
        if text(el, 'length'): detail.append(text(el, 'length') + ' chars')
    if t == 'Number' and text(el, 'precision'):
        detail.append(text(el, 'precision') + ',' + (text(el, 'scale') or '0'))
    if t in ('Lookup', 'MasterDetail'):
        detail.append('to ' + text(el, 'referenceTo'))
    vs = el.find(NS + 'valueSet')
    if vs is not None:
        vals = [v.find(NS + 'fullName').text for v in vs.iter(NS + 'value') if v.find(NS + 'fullName') is not None]
        if vals: detail.append(', '.join(vals))
    if text(el, 'formula'): detail.append('formula')
    desc = (text(el, 'description') or text(el, 'inlineHelpText')).replace('|', '/').replace('\n', ' ')
    return '| `%s` | %s | %s | %s | %s |' % (name, text(el, 'label'), t, '; '.join(detail).replace('|', '/'), desc)

def table(obj):
    d = os.path.join(OBJ, obj, 'fields')
    rows = ['| API name | Label | Type | Details | Description |', '|---|---|---|---|---|']
    if os.path.isdir(d):
        rows += [field_row(os.path.join(d, f)) for f in sorted(os.listdir(d)) if f.endswith('.field-meta.xml')]
    return '\n'.join(rows)

def main():
    objs = sorted(os.listdir(OBJ))
    ours = [o for o in objs if os.path.exists(os.path.join(OBJ, o, o + '.object-meta.xml'))]
    existing = [o for o in objs if o not in ours]
    out = ['# Data Model', '',
           'Every object and field this project adds to the org. Built from the metadata in `force-app` by `tools/data_model.py`; '
           'do not edit this file by hand. Record each change in `docs/data_model_log.md` and rerun the script.', '',
           '**Fields on existing objects** (CQ managed objects and standard objects) are listed first: they change objects this '
           'project does not own, so they need care on upgrade and when moving between orgs.', '']
    out.append(open(os.path.join(ROOT, 'docs/data_model_log.md')).read().strip())
    out += ['', '## Fields added to existing objects', '']
    for o in existing:
        out += ['### ' + o, '', table(o), '']
    snap = os.path.join(ROOT, 'tools/dev_fields_outside_repo.json')
    if os.path.exists(snap):
        rows = json.load(open(snap))
        have = {(o, f.replace('.field-meta.xml', '')) for o in existing
                for f in os.listdir(os.path.join(OBJ, o, 'fields')) if os.path.isdir(os.path.join(OBJ, o, 'fields'))}
        rest = [r for r in rows if (r[0], r[1]) not in have]
        if rest:
            out += ['### In dev but not in this repo', '',
                    'Custom fields on existing objects found in the dev org (snapshot 14 Nov 2026) that this repo does not hold, '
                    'mostly from other work (waivers, LPA, case intake). Listed so nothing on a CQ object goes unnoticed.', '',
                    '| Object | Field | Created |', '|---|---|---|']
            out += ['| `%s` | `%s` | %s |' % (o, f, d) for o, f, d in rest]
            out.append('')
    out += ['## Objects this project created', '']
    for o in ours:
        el = ET.parse(os.path.join(OBJ, o, o + '.object-meta.xml')).getroot()
        out += ['### %s (`%s`)' % (text(el, 'label') or o, o), '']
        if text(el, 'description'): out += [text(el, 'description'), '']
        out += [table(o), '']
    open(os.path.join(ROOT, 'docs/DATA_MODEL.md'), 'w').write('\n'.join(out).rstrip() + '\n')
    print('docs/DATA_MODEL.md: %d objects of ours, %d existing objects' % (len(ours), len(existing)))

if __name__ == '__main__':
    main()
